const filled = (byte: number): Uint8Array => new Uint8Array(32).fill(byte)
const counting = (start: number): Uint8Array => Uint8Array.from({ length: 32 }, (_, i) => start + i)

const macEd = generateEd25519(counting(0x01))
const phoneEd = generateEd25519(counting(0x41))
const mac = deviceId(macEd.publicKey)
const phone = deviceId(phoneEd.publicKey)
const nonce = filled(0xa5)
const pairToken = counting(0x81)

const SM = generateX25519(counting(0x11))
const SP = generateX25519(counting(0x51))
const eM = generateX25519(counting(0x21))
const eP = generateX25519(counting(0x61))
const sealEph = generateX25519(counting(0x31))

const keys = phoneSessionKeys({
  phoneStatic: SP,
  phoneEphemeral: eP,
  macStaticPublic: SM.publicKey,
  macEphemeralPublic: eM.publicKey
})
const macKeys = macSessionKeys({
  macStatic: SM,
  macEphemeral: eM,
  phoneStaticPublic: SP.publicKey,
  phoneEphemeralPublic: eP.publicKey
})
if (toHex(keys.p2m) !== toHex(macKeys.p2m) || toHex(keys.m2p) !== toHex(macKeys.m2p)) {
  throw new Error("phone and Mac derived different session keys")
}

const dh1 = x25519.getSharedSecret(eP.secretKey, eM.publicKey)
const dh2 = x25519.getSharedSecret(eP.secretKey, SM.publicKey)
const dh3 = x25519.getSharedSecret(SP.secretKey, eM.publicKey)
const salt = sha256(
  concat(utf8("arden-e2e/1"), SP.publicKey, SM.publicKey, eP.publicKey, eM.publicKey)
)
const okm = hkdf(sha256, concat(dh1, dh2, dh3), salt, utf8("arden-e2e/1 keys"), 64)

const p2mAad = bodyAad({ sender: phone, receiver: mac })
const m2pAad = bodyAad({ sender: mac, receiver: phone })
const phoneCipher = SessionCipher.forPhone(keys)
const macCipher = SessionCipher.forMac(macKeys)
const frames = (cipher: SessionCipher, aad: Uint8Array, texts: readonly string[]) =>
  texts.map((text, counter) => {
    const nonceBytes = new Uint8Array(12)
    new DataView(nonceBytes.buffer).setBigUint64(4, BigInt(counter))
    return {
      counter,
      nonce: toHex(nonceBytes),
      plaintext_utf8: text,
      plaintext: toHex(utf8(text)),
      body: toHex(cipher.seal(utf8(text), aad))
    }
  })

const sealPlaintext =
  '{"t":"cmd","cid":"0192f0c4-7a00-7000-8000-000000000001","ts":1727000000000,"kind":"send","args":{"text":"hi"}}'
const pushPlaintext =
  '{"kind":"approval","title":"Website","body":"Push the new prices to the site?","session_id":"s1","ask_id":"tool-1"}'
const sealKey = hkdf(
  sha256,
  concat(
    x25519.getSharedSecret(sealEph.secretKey, SM.publicKey),
    x25519.getSharedSecret(SP.secretKey, SM.publicKey)
  ),
  sha256(concat(utf8("arden-seal/1"), sealEph.publicKey, SP.publicKey, SM.publicKey)),
  utf8("seal"),
  32
)

const authBytes = authMessage({ mac, dev: phone, nonce })
const addBytes = addDeviceMessage({ dev: phone, edPublicKey: phoneEd.publicKey })
const removeBytes = removeDeviceMessage({ dev: phone })

